#!/usr/bin/env node
/**
 * The workbook — the task ledger every worker writes to and the owner reads.
 *
 * One file per task (`workbook/tasks/<ID>.json`), so N parallel workers never
 * race on one document, and `done` refuses without evidence. WORKBOOK.md is
 * regenerated on every command and is never hand-edited.
 *
 *   node tools/wb.mjs add W1 --title "..." --owner A1 [--est 30] [--files a.ts]
 *   node tools/wb.mjs start W1 --owner A1
 *   node tools/wb.mjs done W1 --evidence "gate: OK; 8/8 levels audit ok"
 *   node tools/wb.mjs block W1 --note "route.ts needs the gutter spec"
 *   node tools/wb.mjs note W1 --note "chose stable sort"
 *   node tools/wb.mjs list
 */
import { mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const DIR = join(ROOT, 'workbook', 'tasks')
mkdirSync(DIR, { recursive: true })

const [cmd, id] = process.argv.slice(2)
const flag = (name, fallback = '') => {
  const i = process.argv.indexOf(`--${name}`)
  return i > 0 && process.argv[i + 1] !== undefined ? String(process.argv[i + 1]) : fallback
}
const flags = (name) => {
  const out = []
  process.argv.forEach((a, i) => {
    if (a === `--${name}` && process.argv[i + 1] !== undefined) out.push(String(process.argv[i + 1]))
  })
  return out
}

const fileOf = (taskId) => join(DIR, `${taskId}.json`)
const load = (taskId) => JSON.parse(readFileSync(fileOf(taskId), 'utf8'))
const save = (task) => {
  const tmp = `${fileOf(task.id)}.tmp`
  writeFileSync(tmp, `${JSON.stringify(task, null, 2)}\n`)
  renameSync(tmp, fileOf(task.id))
  render()
}

const now = () => new Date().toISOString().replace(/\.\d+Z$/, 'Z')
const STATUSES = ['todo', 'wip', 'done', 'blocked']

function render() {
  const tasks = readdirSync(DIR)
    .filter((f) => f.endsWith('.json'))
    .map((f) => JSON.parse(readFileSync(join(DIR, f), 'utf8')))
    .sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }))
  const counts = STATUSES.map((s) => `${s}=${tasks.filter((t) => t.status === s).length}`).join(' ')
  const rows = tasks.map((t) => {
    const files = (t.files ?? []).map((f) => `\`${f}\``).join('<br>') || '—'
    return `| ${t.id} | ${t.title} | ${t.owner || '—'} | **${t.status}** | ${t.estMin ?? '—'} | ${files} |`
  })
  const evidence = tasks
    .filter((t) => t.evidence)
    .map((t) => `- **${t.id}** — ${t.evidence}`)
    .join('\n')
  const blocks = tasks
    .filter((t) => t.status === 'blocked')
    .map((t) => `- **${t.id}** — ${t.notes.at(-1) ?? 'blocked'}`)
    .join('\n')
  const notes = tasks
    .flatMap((t) => (t.notes ?? []).map((n) => `- **${t.id}** ${n.at} — ${n.text}`))
    .join('\n')
  const body = `# c4-view — WORKBOOK

Generated by \`tools/wb.mjs\`. Do not edit by hand; every status change goes through the script so it
carries an owner, a timestamp and evidence.

**Status:** ${counts}
**Updated:** ${now()}

| Task | Title | Owner | Status | Est (min) | Files |
|---|---|---|---|---|---|
${rows.join('\n')}

## Evidence

${evidence || '_none yet_'}

## Blocked

${blocks || '_none_'}

## Notes / decisions

${notes || '_none_'}
`
  writeFileSync(join(ROOT, 'WORKBOOK.md'), body)
}

switch (cmd) {
  case 'add': {
    if (!id) throw new Error('usage: add <id> --title ... --owner ...')
    const task = {
      id,
      title: flag('title', id),
      owner: flag('owner', ''),
      status: 'todo',
      estMin: Number(flag('est', '0')) || null,
      files: flags('files'),
      evidence: '',
      notes: [],
      startedAt: null,
      endedAt: null,
    }
    if (existsSync(fileOf(id))) throw new Error(`${id} already exists`)
    save(task)
    console.log(`added ${id} — ${task.title}`)
    break
  }
  case 'start': {
    const task = load(id)
    task.status = 'wip'
    task.startedAt = task.startedAt ?? now()
    if (flag('owner')) task.owner = flag('owner')
    save(task)
    console.log(`${id} → wip (${task.owner})`)
    break
  }
  case 'done': {
    const task = load(id)
    const evidence = flag('evidence')
    if (!evidence) {
      console.error(`${id} refused: done needs --evidence "<what proves it>"`)
      process.exit(1)
    }
    task.status = 'done'
    task.evidence = evidence
    task.endedAt = now()
    save(task)
    console.log(`${id} → done — ${evidence}`)
    break
  }
  case 'block': {
    const task = load(id)
    const note = flag('note')
    if (!note) {
      console.error(`${id} refused: block needs --note "<what is missing>"`)
      process.exit(1)
    }
    task.status = 'blocked'
    task.notes.push({ at: now(), text: note })
    save(task)
    console.log(`${id} → blocked — ${note}`)
    break
  }
  case 'note': {
    const task = load(id)
    const note = flag('note')
    if (!note) throw new Error('note needs --note "<text>"')
    task.notes.push({ at: now(), text: note })
    save(task)
    console.log(`${id} noted`)
    break
  }
  case 'list':
  default: {
    render()
    const tasks = readdirSync(DIR).filter((f) => f.endsWith('.json')).length
    console.log(`${tasks} task(s) — WORKBOOK.md regenerated`)
  }
}
